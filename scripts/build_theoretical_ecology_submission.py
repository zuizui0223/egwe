#!/usr/bin/env python3
"""Build an editable, review-facing Theoretical Ecology submission bundle (TeX and Word).

No scientific outcome, figure value, model weight, threshold or seed is recomputed.
The four figures must first be generated by the pinned existing figure builders.
This package intentionally retains author-controlled declaration placeholders.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import zipfile

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor
import cairosvg

ROOT = Path(__file__).resolve().parents[1]
ARTICLE = ROOT / "manuscript/theoretical_ecology_article.md"
COVER = ROOT / "manuscript/theoretical_ecology_cover_letter.md"
TITLE = ROOT / "manuscript/theoretical_ecology_title_page.md"
REFS = ROOT / "manuscript/theoretical_ecology_references.md"
ROUTE = ROOT / "manuscript/THEORETICAL_ECOLOGY_ROUTE_2026-11-07.md"
MANIFEST = ROOT / "manuscript/nee_flagship_source_manifest.json"

SOURCE_FIGURES = [
    "figure1_mathematical_boundaries.svg",
    "figure2_state_separation.svg",
    "figure3_relational_state.svg",
    "figure4_warning_discrimination.svg",
]


def run(*args: str, cwd: Path | None = None) -> None:
    subprocess.run(list(args), cwd=cwd, check=True)


def tune_word_doc(path: Path) -> None:
    """Formatting only; do not modify scientific text or equation content."""
    doc = Document(str(path))
    sec = doc.sections[0]
    sec.top_margin = Inches(0.88)
    sec.bottom_margin = Inches(0.85)
    sec.left_margin = Inches(0.88)
    sec.right_margin = Inches(0.88)
    for nm, size in [("Normal", 10.5), ("Title", 15), ("Heading 1", 13),
                     ("Heading 2", 11.5), ("Heading 3", 10.5)]:
        if nm not in doc.styles:
            continue
        s = doc.styles[nm]
        s.font.name = "Times New Roman"
        s.font.size = Pt(size)
        s.font.color.rgb = RGBColor(0, 0, 0)
    doc.styles["Normal"].paragraph_format.space_after = Pt(6)
    # Word's genuine PAGE field (not a hard-coded page count).
    footer = sec.footer.paragraphs[0]
    footer.alignment = 2
    run = footer.add_run("Page ")
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    run._r.addnext(fld)
    doc.save(str(path))


def pandoc_docx(source: Path, target: Path, resource_dir: Path) -> None:
    run("pandoc", "--standalone",
        "--from=markdown+tex_math_single_backslash",
        "--to=docx", "--resource-path=" + str(resource_dir),
        "-o", str(target), str(source))
    tune_word_doc(target)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--figure-dir", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    source_dir = args.figure_dir.resolve()
    dest = args.output.resolve()
    dest.mkdir(parents=True, exist_ok=True)
    figures = dest / "figures"
    figures.mkdir(exist_ok=True)

    for i, srcname in enumerate(SOURCE_FIGURES, 1):
        src = source_dir / srcname
        if not src.is_file():
            raise FileNotFoundError(f"Required frozen figure missing: {src}")
        shutil.copy2(src, figures / f"Fig{i}.svg")
        cairosvg.svg2png(url=str(src), write_to=str(figures / f"Fig{i}.png"),
                         output_width=2000)
        assert (figures / f"Fig{i}.png").stat().st_size > 5000

    original = ARTICLE.read_text(encoding="utf-8")
    match = re.search(
        r"(?ms)^## Figure captions\s*\n(.*?)\n## References\s*\n",
        original
    )
    if not match:
        raise ValueError("Expected figure caption section not found")
    captions = re.findall(r"(?m)^\*\*Fig\. ([1-4])\*\* (.*)$", match.group(1))
    if len(captions) != 4 or [n for n, _ in captions] != list("1234"):
        raise ValueError(f"Expected four ordered captions; found {len(captions)}")
    # Place full-resolution panel images and author-supplied captions together.
    panels = ["## Figures"]
    for n, caption in captions:
        panels += ["", f"![](figures/Fig{n}.png){{width=6.25in}}", "",
                   f"**Fig. {n}** {caption}", ""]
    staging = original[:match.start()] + "\n".join(panels) + "\n## References\n" + original[match.end():]
    stage_path = dest / "article_review_source.md"
    stage_path.write_text(staging, encoding="utf-8")
    shutil.copy2(ARTICLE, dest / "theoretical_ecology_article_source.md")
    shutil.copy2(COVER, dest / "cover_letter_source.md")
    shutil.copy2(TITLE, dest / "title_page_source.md")
    shutil.copy2(REFS, dest / "references_source.md")
    shutil.copy2(ROUTE, dest / "venue_checklist.md")
    shutil.copy2(MANIFEST, dest / "pinned_scientific_source_manifest.json")

    manuscript = dest / "theoretical_ecology_manuscript.docx"
    pandoc_docx(stage_path, manuscript, dest)
    pandoc_docx(COVER, dest / "cover_letter.docx", ROOT)
    pandoc_docx(TITLE, dest / "title_page.docx", ROOT)

    # Generate the canonical visual proof from editable TeX. LibreOffice does
    # not faithfully render all Word OMML math; an LO-generated PDF can silently
    # omit entire equations. The journal explicitly accepts LaTeX submissions.
    tex = dest / "theoretical_ecology_manuscript.tex"
    run("pandoc", "--standalone",
        "--from=markdown+tex_math_single_backslash",
        "--to=latex", "--resource-path=" + str(dest),
        "-V", "geometry:margin=0.9in", "-V", "fontsize=10pt",
        "-V", "colorlinks=false",
        "-o", str(tex), str(stage_path))
    latex = shutil.which("xelatex")
    if not latex:
        raise RuntimeError("XeLaTeX required: canonical PDF must render all display equations")
    for _ in range(2):
        run(latex, "-interaction=nonstopmode", "-halt-on-error",
            "-file-line-error", "-output-directory=" + str(dest), str(tex),
            cwd=dest)
    pdf = tex.with_suffix(".pdf")
    if not pdf.is_file() or pdf.stat().st_size < 10000:
        raise RuntimeError("Canonical TeX PDF was not generated")

    # Read-back checks inspect generated Word and PDF without modifying content.
    readback = Document(str(manuscript))
    words = " ".join(p.text for p in readback.paragraphs)
    for token in ("1,037/1,037", "0.2543", "0.92734", "+0.02135",
                  "0.23253", "Statements and Declarations"):
        if token not in words:
            raise AssertionError("DOCX lost evidence-critical token " + token)
    if len(readback.inline_shapes) < 4:
        raise AssertionError("Expected four embedded figure panels")
    if shutil.which("pdftotext"):
        extracted = subprocess.check_output(["pdftotext", str(pdf), "-"], text=True)
        for token in ("0.2543", "0.92734", "+0.02135", "sigmoid"):
            if token not in extracted:
                raise AssertionError("PDF lost evidence-critical token " + token)
        if "$" in extracted or r"\operatorname{sigmoid}" in extracted:
            raise AssertionError("PDF contains literal/failed math markup")

    # Store checksums and the actual open human gates in the distribution bundle.
    notice = """THEORETICAL ECOLOGY -- REVIEW-READY DRAFT, NOT PORTAL-SUBMITTED

Evidence and figures: frozen existing model results; no outcome recalibration.
Prepared editable LaTeX source and correctly typeset PDF, plus a Word editing draft,
four full-resolution figures, cover letter, title page, source Markdown,
provenance manifest and checklist. Use LaTeX+PDF for the journal submission
unless the Word OMML equations are separately verified in Microsoft Word.
Do NOT use a LibreOffice-exported Word PDF: it can hide display equations.

USER/COAUTHOR ACTIONS REMAIN:
- Approve final author order, affiliations, corresponding author, contributions.
- Verify funding, competing interests, acknowledgements and AI-use disclosure.
- Screen all five potential reviewers for conflicts and confirm contact details.
- Read final author-proof PDF and approve journal portal declarations.
- Check manuscript exclusivity and institutional requirements.
- Submit via publisher account; this workflow does not submit or pay fees.

The source-manifest and figure builders retain historical NEE filenames, but
the ACTIVE TARGET is Theoretical Ecology. Old NEE format checks cannot certify
this journal's portal acceptance.
"""
    (dest / "README_DRAFT_AND_HUMAN_GATES.txt").write_text(notice)
    checksums = {}
    for f in sorted(dest.rglob("*")):
        if f.is_file() and f.suffix != ".zip":
            checksums[str(f.relative_to(dest))] = hashlib.sha256(f.read_bytes()).hexdigest()
    (dest / "MANIFEST.sha256.json").write_text(
        json.dumps(checksums, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"word_paragraphs": len(readback.paragraphs),
                      "figures": len(readback.inline_shapes),
                      "pdf_bytes": pdf.stat().st_size,
                      "total_files": len(checksums)}, indent=2))
    # Archive lives OUTSIDE packet to avoid ZIP self-inclusion.
    archive = dest.with_suffix(".zip")
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as out:
        for file in sorted(dest.rglob("*")):
            if file.is_file():
                out.write(file, str(file.relative_to(dest.parent)))
    print(f"Review packet: {archive}")


if __name__ == "__main__":
    main()
